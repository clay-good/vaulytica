/**
 * The bounded task a person has to do, derived from a report they can open.
 *
 * BUILD_PROGRESS step 37's remainder is the one item blocked on a human rather
 * than on engineering: **somebody has to listen to a screen reader read the
 * produced DOCX's tables.** No automated check substitutes for that, and this
 * script does not pretend to be one. What it removes is the part that was
 * unbounded — "verify the tables" names neither the tables nor what a pass
 * sounds like, and step 37 asked for verification of a table that is NEVER
 * PRODUCED until 9.900.0 corrected it.
 *
 * So the script is GENERATED from a real `--format docx` run: every table in
 * the order a reader meets it, its header cells as the document actually
 * writes them, and the sentence the reader must hear. A table added or renamed
 * changes this file on the next run, which is the point — a hand-written
 * checklist would have gone stale the same way the step's own wording did.
 *
 * Usage: `npm run a11y:script` → docs/a11y/listening-script.md
 */
import { mkdtemp, readFile, readdir, rm, writeFile, mkdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { strFromU8, unzipSync } from "fflate";
import { runAnalyze } from "../cli/run.js";

const SPECIMEN = join(process.cwd(), "tests", "fixtures", "specimens", "mutual-nda-letter.txt");
/**
 * `VAULYTICA_A11Y_OUT` sends the script somewhere else. The staleness guard
 * uses it to compare without rewriting the tracked file: a test that mutates
 * `docs/` leaves the working tree dirty on failure, which in this repo — where
 * goldens are regenerated by hand — is a trap worth not setting.
 */
const OUT =
  process.env.VAULYTICA_A11Y_OUT ?? join(process.cwd(), "docs", "a11y", "listening-script.md");
const OUT_DIR = dirname(OUT);

/** The cell texts of one `<w:tr>`, in order. */
function cellsOf(rowXml: string): string[] {
  return [...rowXml.matchAll(/<w:tc>([\s\S]*?)<\/w:tc>/g)].map((tc) =>
    [...tc[1]!.matchAll(/<w:t(?:\s[^>]*)?>([\s\S]*?)<\/w:t>/g)]
      .map((t) => t[1]!)
      .join("")
      .replace(/&amp;/g, "&")
      .replace(/&lt;/g, "<")
      .replace(/&gt;/g, ">")
      .trim(),
  );
}

type TableFacts = { header: string[]; marked: boolean; bodyRows: number; firstBody: string[] };

function tablesOf(xml: string): TableFacts[] {
  return [...xml.matchAll(/<w:tbl>([\s\S]*?)<\/w:tbl>/g)].map((m) => {
    const body = m[1]!;
    const rows = [...body.matchAll(/<w:tr[^>]*>([\s\S]*?)<\/w:tr>/g)].map((r) => r[1]!);
    const head = rows[0] ?? "";
    return {
      header: cellsOf(head),
      marked: /<w:tblHeader(?:\s*\/>|\s+w:val="(?:true|1)"\s*\/>)/.test(head),
      bodyRows: Math.max(0, rows.length - 1),
      firstBody: rows[1] ? cellsOf(rows[1]) : [],
    };
  });
}

async function main(): Promise<void> {
  const dir = await mkdtemp(join(tmpdir(), "vaulytica-a11y-"));
  try {
    await runAnalyze([SPECIMEN, "--format", "docx", "--out", dir]);
    const file = (await readdir(dir)).find((f) => f.endsWith(".docx"));
    if (!file) throw new Error("the analysis produced no .docx to listen to");
    const xml = strFromU8(unzipSync(await readFile(join(dir, file)))["word/document.xml"]!);
    const tables = tablesOf(xml);
    if (tables.length === 0) throw new Error("the produced report contains no tables");

    const lines: string[] = [
      "# Screen-reader listening script",
      "",
      "> Generated by `npm run a11y:script` from a real `--format docx` run over",
      "> `mutual-nda-letter.txt`. **Do not hand-edit** — a table added or renamed",
      "> changes this file on the next run.",
      "",
      "BUILD_PROGRESS step 37's remainder is the one item blocked on a person, not",
      "on engineering. This is that task, bounded: " +
        String(tables.length) +
        " tables, named, with the",
      "sentence each one must produce.",
      "",
      "⚠️ **Nine is this document's count, not the universe.** The tables a report",
      "carries depend on what the document triggers: an NDA produces no insurance",
      "summary, no transfer table and no subprocessor inventory. Re-run this",
      "script against a certificate of insurance or a DPA to get those, and",
      "listen to them too before marking the step complete.",
      "",
      "## What a pass sounds like",
      "",
      "In a table with a marked heading row, a screen reader announces the COLUMN",
      "NAME before the value when you move into the body — “Governing law,",
      "Delaware”, not “Delaware”. A failure is the bare value, with no column",
      "name, because the reader does not know row 1 is a heading.",
      "",
      "Word repeats a marked heading row across a page break. If a table spans",
      "pages and the second page starts straight into data, the row is not marked.",
      "",
      "## Setup",
      "",
      "1. `npm run cli -- tests/fixtures/specimens/mutual-nda-letter.txt --format docx --out /tmp/a11y`",
      "2. Open the `.docx` in Word (not a viewer — the heading-row repeat is Word's).",
      "3. Start Narrator (Windows, `Ctrl`+`Win`+`Enter`) or VoiceOver (macOS, `Cmd`+`F5`).",
      "",
      "## The tables, in the order a reader meets them",
      "",
    ];

    tables.forEach((t, i) => {
      const name = t.header.filter(Boolean).join(" · ") || "(no header text)";
      lines.push(`### ${i + 1}. ${name}`);
      lines.push("");
      lines.push(
        `- Heading row marked in the XML: **${t.marked ? "yes" : "NO — this is a defect, stop and report it"}**`,
      );
      lines.push(`- Body rows: ${t.bodyRows}`);
      if (t.firstBody.length > 0 && t.header.length > 0) {
        // Skip a row-number column: "#, 1" illustrates nothing. The first
        // column whose header is a WORD and whose value is not just digits is
        // what makes the expected sentence recognizable.
        const at = t.header.findIndex(
          (h, k) => /[A-Za-z]{2}/.test(h) && /[A-Za-z]/.test(t.firstBody[k] ?? ""),
        );
        const col = at >= 0 ? t.header[at]! : (t.header.find(Boolean) ?? "");
        const val = at >= 0 ? t.firstBody[at]! : (t.firstBody.find(Boolean) ?? "");
        if (col && val) {
          lines.push(
            `- Move into the first body row. Expect to hear “**${col}, ${val.slice(0, 60)}**” or the equivalent in your reader's phrasing.`,
          );
        }
      }
      lines.push("- [ ] Column name announced with the value");
      lines.push("- [ ] If it spans a page break, the heading row repeats");
      lines.push("");
    });

    lines.push("## When every box is ticked");
    lines.push("");
    lines.push(
      "Record the date, the reader and its version on BUILD_PROGRESS step 37 and",
      "mark the row complete. If any box fails, the finding belongs in the",
      "CHANGELOG with the table named — the XML assertion in",
      "`tests/integration/cli-docx-report.test.ts` covers the MARKING, so a",
      "failure here is something that assertion cannot see.",
      "",
    );

    await mkdir(OUT_DIR, { recursive: true });
    await writeFile(OUT, lines.join("\n"), "utf8");
    process.stdout.write(`Wrote ${OUT} (${tables.length} tables)\n`);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

await main();
